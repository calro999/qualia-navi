def clean_product_name_for_seo(raw_name: str) -> str:
    if not raw_name:
        return ""

    # 1. 不要なブラケット【...】や[...]の装飾文字のみ除去（SEOキーワードや商品名は維持）
    cleaned = re.sub(r'【[^】]+】|\[[^\]]+\]', '', raw_name).strip()

    # 2. 「＼...／」 などの目立つ装飾記号を除去
    cleaned = re.sub(r'＼[^／]+／', '', cleaned).strip()
    
    # 3. 先頭や末尾の記号類をトリム
    cleaned = re.sub(r'^[★☆♪■◆!！\s\-_]+', '', cleaned).strip()

    # 4. 切り出し処理（最大35文字程度でSEO商品名をたっぷり活かす）
    if len(cleaned) <= 35:
        result = cleaned
    else:
        # 35文字時点で自然に区切れる場所を探す（スペースや全角スペースなど）
        sub = cleaned[:35]
        # 最後のスペースまたは全角スペースで区切る
        last_space = max(sub.rfind(' '), sub.rfind('　'))
        if last_space > 10:  # あまりに短くなりすぎない場合
            result = sub[:last_space].strip()
        else:
            result = sub.strip()

    # 5. 【超重要：セーフティ】もし結果が3文字未満（「ベ」「ネ」など）になってしまった場合
    if len(result) < 3:
        # 元の文字からブラケットのみ消した文字列を25文字そのまま使う
        result = cleaned[:25].strip() if len(cleaned) >= 25 else cleaned

    return result

