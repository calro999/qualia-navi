3. **乾燥しているのに裸足でフローリングを歩く**  
   冷たいフローリングとの摩擦と静電気、冷気は角質の硬化を猛烈に加速させます。クリームを塗った後は、綿やシルクの靴下、または専用の保湿ソックスを着用して保温・保湿を徹底しましょう。

