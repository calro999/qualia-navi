超音波トリートメントアイロンのプレートに水を数滴垂らすと、熱くないのに水滴が一瞬で「白い超微細ミスト」になって気化する様子が確認できます。これと同じ現象が髪の表面で起きています。手で塗っただけでは分子が大きすぎてキューティクルの表面を滑るだけだったトリートメントの油分やアミノ酸が、超音波の振動によって瞬時にナノサイズへとクラッシュされ、キューティクルの隙間をすり抜けて毛髪内部へグイグイ吸い込まれていくのです。

