   化粧水を重ねづけした後は、必ず両手で優しく包み込み、肌表面が「吸いつくようなもっちり感（ベタつきゼロ）」になるまで1〜2分置くのが鉄則です。

ステップ2: 【ポアプライマーは「下から上へ、くるくると毛穴の向きに逆らって」入れ込む】
   顔の毛穴は重力によって「下向き」に開いています。
   下地を上から下へサーッと滑らせるだけでは毛穴の窪みをカバーできません。
   少量を指先に取り、小鼻や頬の毛穴に対して「下から上へ、優しく円を描くように」くるくると馴染ませることで、光拡散パウダーが均一に毛穴にフィットします。

ステップ3: 【スポンジで余分な油分を「垂直タッピング」でオフする】
   下地を全顔に馴染ませた後、清潔なメイクスポンジ（水を含ませて固く絞ったスポンジがベスト）で、
   小鼻のキワやフェイスラインを優しく垂直にポンポンと叩き込みます。
   余分な下地の厚みを吸収することで、ファンデーションとの密着強度が劇的に向上します。

ステップ4: 【ファンデーションは毛穴エリアを「最後に薄膜で」仕上げる】
   毛穴を隠したいからとファンデーションを毛穴部分から塗り始めるのは毛穴落ちの最大要因です！
   ファンデーションは頬の広い面から塗り始め、スポンジに残ったごくごく微量のファンデーションを最後に毛穴部分へトントンと置く程度に留めるのが、一日中崩れないプロの極意です。
