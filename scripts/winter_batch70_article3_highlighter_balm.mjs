パウダーハイライトのツヤは、細かく砕いたマイカ（雲母）や合成パールの「粒子の散乱光」によって生まれます。一方、バームやスティックのツヤは、植物オイルやエモリエント成分が肌表面に均一な油膜を形成し、光を鏡のように反射する「正反射（屈折光）」によって生まれます。そのため、ギラギラとした人工的なラメ感にならず、「まるで肌そのものが水分をたっぷり含んで発光しているかのような生々しい透明感」が手に入ります。

