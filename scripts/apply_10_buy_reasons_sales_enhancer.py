# 2. 全商品の cons を「不安解消・使いこなし技」へと格上げ
def polish_con_to_sales_advice(con_text):
    if not con_text:
        return '少量から手に取り、肌状態に合わせて優しくなじませると、本来の美しさが一日中持続します。'
    
    # 既にアドバイス形式になっているものはそのまま活かす
    if 'おすすめ' in con_text or '秘訣' in con_text or 'ベスト' in con_text or 'コツ' in con_text:
        return con_text
    
    # 品薄・在庫に関する懸念
    if '品薄' in con_text or '欠品' in con_text or '在庫' in con_text:
        return '注目の大人気アイテムのため、楽天市場のお買い物マラソンやセール期間中は公式ショップの在庫を早めに確保しておくと安心です。'
    
    # 価格に関する懸念
    if '価格' in con_text or '高' in con_text or 'プチプラ' in con_text:
        return 'デパコス級の上質な成分設計ですが、ごく少量で驚くほど伸びるため、1日あたりで換算すると極めて満足度の高い賢い投資になります。'
        
    # 香りに関する懸念
    if '香' in con_text:
        return '洗練された心地よいアロマが広がるため、気分をリフレッシュしたいリラックスタイムにひときわ心地よく寄り添います。'
        
    # テクスチャー・塗布量に関する懸念
    if '量' in con_text or '重' in con_text or 'ベタ' in con_text or 'ヨレ' in con_text or '厚' in con_text:
        return '肌なじみが非常に良いため、まずは少量から薄くハンドプレスするように重ねることで、ムラなく端正なツヤが一日中続きます。'
        
    # 汎用的な前向きアドバイス化
    clean = con_text.replace('ため、', 'ため、').replace('が、', 'が、')
    return f"{clean}（肌コンディションに合わせて適量をなじませることで、本来のパフォーマンスを最大限に引き出せます）"

