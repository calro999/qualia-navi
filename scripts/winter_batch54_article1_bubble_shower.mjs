気泡がマイナスの電荷（負電位）を帯びているため、プラスの電荷を帯びた皮脂汚れやメイク残り、古い角質を磁石のように引き寄せて洗い流します。同時に、バブルが弾ける際のエネルギーで角層の水分含有量を高め、シャワー直後から吸い付くようなしっとり感をもたらします。

