def load_dotenv(dotenv_path):
    if os.path.exists(dotenv_path):
        with open(dotenv_path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    k, v = line.split('=', 1)
                    k = k.strip()
                    v = v.strip().strip('"\'')
                    if k and v and k not in os.environ:
                        os.environ[k] = v

def load_yaml_config(filepath):
    if not os.path.exists(filepath):
        return []
    topics = []
    current_topic = None
    with open(filepath, 'r', encoding='utf-8') as f:
        for line in f:
            line_str = line.strip()
            if not line_str or line_str.startswith('#'):
                continue
            if line_str.startswith('- id:') or line_str.startswith('- topic'):
                if current_topic:
                    topics.append(current_topic)
                current_topic = {}
                parts = line_str.replace('- ', '').split(':', 1)
                if len(parts) == 2:
                    current_topic[parts[0].strip()] = parts[1].strip().strip('"\'')
            elif current_topic and ':' in line_str:
                parts = line_str.split(':', 1)
                key = parts[0].strip()
                val = parts[1].strip().strip('"\'')
                if val.lower() == 'true':
                    val = True
                elif val.lower() == 'false':
                    val = False
                current_topic[key] = val
        if current_topic:
            topics.append(current_topic)

    # 徹底的な重複除去（ID & Keyword）
    seen_ids = set()
    seen_keywords = set()
    unique_topics = []
    import re
    for t in topics:
        tid = t.get('id', '')
        kw = t.get('keyword', '')
        norm_kw = re.sub(r'[\s\u3000【】\[\]（）()]', '', kw.lower()) if kw else ''
        if tid and tid in seen_ids:
            continue
        if norm_kw and norm_kw in seen_keywords:
            continue
        if tid:
            seen_ids.add(tid)
        if norm_kw:
            seen_keywords.add(norm_kw)
        unique_topics.append(t)

    return unique_topics

def fetch_rakuten_item(app_id, access_key, affiliate_id, keyword):
    print(f"Fetching from Rakuten API: {keyword}")
    if not app_id or app_id == 'DUMMY':
        print("Warning: RAKUTEN_APP_ID is DUMMY. Cannot fetch real data.")
        return None

    base_url = "https://openapi.rakuten.co.jp/ichibams/api/IchibaItem/Search/20260401"
    params = {
        "applicationId": app_id,
        "accessKey": access_key,
        "affiliateId": affiliate_id,
        "keyword": keyword,
        "sort": "standard",
        "hits": 1,
        "format": "json"
    }
    url = f"{base_url}?{urllib.parse.urlencode(params)}"
    
    import time
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(req, timeout=10) as res:
                data = json.loads(res.read().decode('utf-8'))
                if data.get("Items"):
                    item = data["Items"][0]["Item"]
                    image_url = ""
                    if item.get("mediumImageUrls"):
                        image_url = item["mediumImageUrls"][0]["imageUrl"]
                        if "?_ex=" in image_url:
                            image_url = image_url.split("?")[0]
                    
                    affiliate_url = item.get("affiliateUrl")
                    if image_url and affiliate_url:
                        return {
                            "image_url": image_url,
                            "affiliate_url": affiliate_url,
                            "price": f"{item.get('itemPrice', 0)}円"
                        }
            time.sleep(1)
        except Exception as e:
            print(f"API Error (Attempt {attempt+1}): {e}")
            time.sleep(1)
            
    print(f"Failed to fetch valid item for {keyword} after 3 attempts")
    return None

def ensure_local_product_image(image_url, save_filename, public_img_dir):
    os.makedirs(public_img_dir, exist_ok=True)
    local_path = os.path.join(public_img_dir, save_filename)
    rel_path = f"/images/products/{save_filename}"

    if not image_url:
        return rel_path

    headers = {
        'User-Agent': 'Mozilla/5.0'
    }

    try:
        req = urllib.request.Request(image_url, headers=headers)
        with urllib.request.urlopen(req, timeout=10) as res:
            if res.status == 200:
                data = res.read()
                if len(data) > 1000:
                    with open(local_path, 'wb') as f:
                        f.write(data)
                    print(f"[OK] Saved local product image -> {local_path}")
                    return rel_path
    except Exception as e:
        print(f"[WARNING] Image download failed: {e}")

    return rel_path

