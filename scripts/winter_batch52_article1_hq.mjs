    D --> E["黒色メラニンの蓄積（シミ・肝斑）"]
    E --> F["【メラニン還元・無色化】ピュアビタミンC・ハイドロキノン"]
    E --> G["【ターンオーバー促進・排出】純粋レチノール・ピーリングAHA"]
    F --> H["澄み渡る発光透明肌"]
    G --> H
