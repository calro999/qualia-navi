クレンジングオイルがほぼ100%オイルであるのに対し、ミルクやクリームクレンジングは**水分と油分が乳化された構造（エマルジョン）**を持っています。メイクの油分を浮かせながらも、水相に含まれる美容液成分や保湿成分（ヒアルロン酸、コラーゲン、植物エキス）が肌の角層にとどまるため、すすいだ後につっぱり感が生まれません。

