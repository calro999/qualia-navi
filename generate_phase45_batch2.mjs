async function main() {
  const newArticles = [];
  const existingIds = new Set(articlesData.map(a => a.id));

  for (const def of articleDefs) {
    if (existingIds.has(def.id)) {
      console.log(`⏭️ [既存スキップ] ${def.id}`);
      continue;
    }

    console.log(`\n🔍 [記事生成開始] ${def.id}`);
    console.log(`   対象クエリ: ${def.queryTarget}`);
    console.log(`   検索キーワード: ${def.searchKeyword}`);

    const products = await fetchRakutenItems(def.searchKeyword, 12);

    if (products.length === 0) {
      console.warn(`⚠️ [スキップ] 商品取得失敗: ${def.id}`);
      await sleep(2000);
      continue;
    }

    console.log(`✅ [商品取得完了] ${products.length}件取得`);

    const content = await buildArticleContent(def, products);
    const top10 = products.slice(0, 10);

    const article = {
      id: def.id,
      title: def.title,
      description: def.description,
      content,
      category: def.category,
      tags: def.tags,
      author: def.author,
      createdAt: '2026-08-30',
      updatedAt: def.updatedAt,
      image: top10[0]?.imageUrl || '',
      affiliateUrl: top10[0]?.affiliateUrl || '',
      price: top10[0]?.price || '',
      itemCount: top10.length,
      featured: def.featured
    };

    newArticles.push(article);
    console.log(`✅ [記事生成完了] ${def.title.slice(0, 40)}...`);
    await sleep(1500);
  }

  console.log(`\n📝 [articles.json 更新中] 新規 ${newArticles.length}件 を追加...`);
  articlesData.unshift(...newArticles);
  fs.writeFileSync(articlesJsonPath, JSON.stringify(articlesData, null, 2), 'utf-8');

  console.log(`\n🎉 [完了] Phase 45 Batch2 コスメクエリ特集記事 ${newArticles.length}件 を追加！`);
  console.log(`   現在の総記事数: ${articlesData.length}件`);
}

main().catch(e => {
  console.error('❌ [致命的エラー]:', e);
  process.exit(1);
});
